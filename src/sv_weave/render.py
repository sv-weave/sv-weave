"""Stage 6, Render: the woven model as SV text, with a line map (design §7.1).

The line map holds one entry per contributed fragment: the 1-based first and last
woven line it occupies, and its ``Origin``. Verify uses it to point a diagnostic in the
woven code back at the weaver that produced it.
"""
import dataclasses as dc
from typing import Dict, List, Optional, Tuple

from .__version__ import __version__
from .weave.model import MethodSlot, Origin, SvFragment, WovenClass, WovenPackage

INDENT = "  "
GENERATED_PREFIX = "// Generated by sv-weave"
HEADER = GENERATED_PREFIX + " %s. Do not edit." % __version__


@dc.dataclass
class LineSpan:
    first: int
    last: int
    origin: Origin


@dc.dataclass
class RenderedFile:
    name: str
    text: str
    line_map: List[LineSpan] = dc.field(default_factory=list)

    def origin_at(self, line: int) -> Optional[Origin]:
        for s in self.line_map:
            if s.first <= line <= s.last:
                return s.origin
        return None


class Emitter:
    def __init__(self):
        self.lines: List[str] = []
        self.spans: List[LineSpan] = []
        self.level = 0

    def line(self, text: str = ""):
        self.lines.append((INDENT * self.level + text) if text else "")

    def frag(self, frag: SvFragment):
        first = len(self.lines) + 1
        for ln in frag.lines():
            self.line(ln.rstrip())
        if frag.origin is not None and len(self.lines) >= first:
            self.spans.append(LineSpan(first, len(self.lines), frag.origin))

    def indent(self):
        self.level += 1

    def dedent(self):
        self.level -= 1

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def render_slot(e: Emitter, slot: MethodSlot):
    sig = slot.sig
    e.line(sig.header(virtual=slot.virtual))
    e.indent()
    if slot.ret_var is not None and (slot.has_super_call or slot.result is None):
        e.line("%s %s;" % (sig.ret, slot.ret_var))
    for f in slot.decl.ordered():
        e.frag(f)
    for f in slot.pre.ordered():
        e.frag(f)
    if slot.has_super_call:
        call = "super.%s(%s);" % (sig.name, ", ".join(sig.arg_names))
        if slot.ret_var is not None:
            call = "%s = %s" % (slot.ret_var, call)
        e.line(call)
    for f in slot.post.ordered():
        e.frag(f)
    if sig.ret is not None:
        e.line("return %s;" % (slot.result if slot.result is not None else slot.ret_var))
    e.dedent()
    e.line("%s : %s" % ("endtask" if sig.task else "endfunction", sig.name))


def render_class(e: Emitter, wc: WovenClass):
    e.line("// %s, profile%s %s" % (wc.cls.qname, "s" if wc.also_profiles else "",
                                    ", ".join(wc.profiles)))
    # A woven class that leaves a pure method unimplemented is abstract itself.
    e.line("%sclass %s extends %s;" % ("" if wc.concrete else "virtual ", wc.name, wc.extends))
    e.indent()
    blocks = 0
    for fd in wc.fields:
        e.frag(SvFragment(fd.text, fd.origin))
        blocks += 1
    for it in wc.items:
        if blocks:
            e.line()
        e.frag(it.frag)
        blocks += 1
    if wc.ctor is not None:
        if blocks:
            e.line()
        e.line("function new(%s);" % ", ".join(wc.ctor.args))
        e.indent()
        e.line("super.new(%s);" % ", ".join(wc.ctor.arg_names))
        e.dedent()
        e.line("endfunction : new")
        blocks += 1
    for slot in wc.slots.values():
        if blocks:
            e.line()
        render_slot(e, slot)
        blocks += 1
    e.dedent()
    e.line("endclass : %s" % wc.name)


def content_key(wc: WovenClass) -> str:
    """The class's rendered text, independent of its name and profile: two woven
    classes with the same key are interchangeable."""
    e = Emitter()
    render_class(e, wc)
    lines = e.lines[1:]                     # drop the profile comment
    return "\n".join(lines).replace(wc.name, "__WOVEN__")


def register_items(wpkg: WovenPackage, stmts, static: bool):
    """``__register()`` for a woven package, plus the static holder if asked for."""
    lines = ["bit __sv_weave_registered;",
             "",
             "// Registers everything this package provides. Called by",
             "// sv_weave_init_pkg::sv_weave_init(); safe to call more than once.",
             "function automatic void __register();",
             "  if (__sv_weave_registered) return;",
             "  __sv_weave_registered = 1;"]
    lines += ["  " + l for st in stmts for l in st.split("\n")]
    lines += ["endfunction : __register"]
    wpkg.items.append(SvFragment("\n".join(lines), None))
    if static:
        wpkg.items.append(SvFragment("""
            // registration: static. Registers at static initialisation, on simulators
            // that initialise statics of classes nothing references.
            function automatic bit __register_static();
              __register();
              return 1;
            endfunction : __register_static

            class __sv_weave_static_reg;
              static bit m_done = __register_static();
            endclass : __sv_weave_static_reg""", None))


def render_package(wpkg: WovenPackage) -> RenderedFile:
    e = Emitter()
    e.line(HEADER)
    for l in wpkg.preamble:
        e.line(l)
    e.line("package %s;" % wpkg.name)
    e.indent()
    for imp in wpkg.imports:
        e.line("import %s::*;" % imp)
    for wc in wpkg.classes:
        e.line()
        render_class(e, wc)
    for item in wpkg.items:
        e.line()
        e.frag(item)
    e.dedent()
    e.line()
    e.line("endpackage : %s" % wpkg.name)
    return RenderedFile(wpkg.name + ".sv", e.text(), e.spans)


def render_file(name: str, frag: SvFragment) -> RenderedFile:
    """A weaver's whole file (``DesignCtx.add_file``): the header, then its text."""
    e = Emitter()
    e.line(HEADER)
    e.frag(frag)
    return RenderedFile(name, e.text(), e.spans)


# The init package and module, one per file (a file named after what it declares
# keeps Verilator's DECLFILENAME quiet). In compile order.
INIT_PKG_FILE = "sv_weave_init_pkg.sv"
INIT_MOD_FILE = "sv_weave_init_m.sv"
INIT_FILES = (INIT_PKG_FILE, INIT_MOD_FILE)
# The single init file sv-weave 0.1 wrote; recognised so chained runs still detect it.
LEGACY_INIT_FILE = "sv_weave_init.sv"


def render_init_pkg(packages) -> str:
    """``sv_weave_init_pkg`` (design §8.4): ``sv_weave_init()`` calls every woven
    package's ``__register()``, in order."""
    e = Emitter()
    e.line(HEADER)
    e.line("package sv_weave_init_pkg;")
    e.indent()
    e.line()
    e.line("// Registers everything the woven packages provide. Idempotent.")
    e.line("function automatic void sv_weave_init();")
    e.indent()
    for wp in packages:
        e.line("%s::__register();" % (wp if isinstance(wp, str) else wp.name))
    e.dedent()
    e.line("endfunction : sv_weave_init")
    e.line()
    e.line("function automatic bit sv_weave_init_bit();")
    e.indent()
    e.line("sv_weave_init();")
    e.line("return 1;")
    e.dedent()
    e.line("endfunction : sv_weave_init_bit")
    e.dedent()
    e.line()
    e.line("endpackage : sv_weave_init_pkg")
    return e.text()


def render_init_m() -> str:
    """``sv_weave_init_m``: instantiating it runs ``sv_weave_init()`` from a static
    initialiser, before any ``initial`` block."""
    e = Emitter()
    e.line(HEADER)
    e.line("// Instantiate once (or add as an extra top): registers at static initialisation.")
    e.line("module sv_weave_init_m;")
    e.indent()
    e.line("/* verilator lint_off UNUSEDSIGNAL */")
    e.line("bit m_done = sv_weave_init_pkg::sv_weave_init_bit();")
    e.line("/* verilator lint_on UNUSEDSIGNAL */")
    e.dedent()
    e.line("endmodule : sv_weave_init_m")
    return e.text()


def render_init(packages) -> Dict[str, str]:
    """The init files, ``{name: text}`` in compile order, registering ``packages``
    (woven packages or their names). A testbench instantiates ``sv_weave_init_m`` or
    calls ``sv_weave_init_pkg::sv_weave_init()`` itself."""
    return {INIT_PKG_FILE: render_init_pkg(packages), INIT_MOD_FILE: render_init_m()}


INIT_STUB_NAME = "<sv-weave init stub>"


def init_stub() -> str:
    """Load-time stand-in for the init files. User code may instantiate
    sv_weave_init_m or call sv_weave_init_pkg::sv_weave_init() before anything has
    been generated; the stub has the same interface and no registrations."""
    return "".join(render_init([]).values())
