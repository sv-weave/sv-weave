"""Stage 7, Verify (design §7.3).

Levels:
- ``full``: re-elaborate the user's syntax trees (reused from Load) with the runtime
  and the woven buffers, map diagnostics in woven code back to the contributing
  weaver, run the rand-safety rules, and check structure (woven overrides really
  override; registered classes are concrete);
- ``syntax``: parse the woven buffers alone and run the rand-safety rules;
- ``off``: nothing.

A ``full`` pass is recorded in the manifest with the input and output hashes; a later
run with the same hashes skips verification (``cached``).
"""
import dataclasses as dc
import os
from typing import Dict, List, Optional

import pyslang
from pyslang import ast as A
from pyslang import syntax as S

from .diag import Diag, Severity, SrcLoc
from .frontend.loader import convert_diags
from .render import INIT_STUB_NAME, RenderedFile
from .verify_rules import check_rules
from .weave.model import MethodSlot

FAILED_DIR = ".failed"


@dc.dataclass
class VerifyResult:
    status: str                       # full | syntax | off | cached
    diags: List[Diag] = dc.field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not any(d.severity == Severity.ERROR for d in self.diags)


def _map(d: Diag, rf: Optional[RenderedFile], shown_path: str) -> Diag:
    """A diagnostic in woven code, attributed to the fragment that produced it."""
    if d.loc is None or rf is None:
        return d
    where = "%s:%d" % (shown_path, d.loc.line)
    origin = rf.origin_at(d.loc.line)
    if origin is not None and origin.file:
        return Diag(d.severity, "%s [woven code %s, from %s]" % (d.msg, where, origin),
                    SrcLoc(origin.file, origin.line), d.code)
    who = "binding '%s'" % origin.contributor if origin is not None else "sv-weave"
    return Diag(d.severity, "%s [woven code %s, generated by %s]" % (d.msg, where, who),
                SrcLoc(shown_path, d.loc.line, d.loc.col), d.code)


def _woven_files(res) -> List[RenderedFile]:
    out = list(res.rendered)
    for name, text in res.extra_files.items():
        out.append(RenderedFile(name, text))
    return out


def shown_path(res, name: str) -> str:
    """Where the user can look at a woven file: in .failed/ until it is written."""
    return os.path.join(res.out_dir, FAILED_DIR, name)


def verify_syntax(res) -> VerifyResult:
    diags: List[Diag] = []
    for rf in _woven_files(res):
        path = shown_path(res, rf.name)
        tree = S.SyntaxTree.fromText(rf.text, pyslang.SourceManager(), rf.name, path)
        for d in convert_diags(tree.sourceManager, tree.diagnostics):
            if d.severity == Severity.ERROR:
                diags.append(_map(d, rf, path))
        diags.extend(check_rules(tree, rf, res.cfg, path))
    return VerifyResult("syntax", diags)


def verify_full(res) -> VerifyResult:
    loaded = res.loaded
    sm = loaded.source_manager
    comp = A.Compilation(loaded.bag) if loaded.bag is not None else A.Compilation()
    if loaded.file_tree is not None:
        comp.addSyntaxTree(loaded.file_tree)
    for name, t in loaded.text_trees:
        if name != INIT_STUB_NAME:
            comp.addSyntaxTree(t)
    by_path: Dict[str, RenderedFile] = {}
    trees = []
    for rf in _woven_files(res):
        path = shown_path(res, rf.name)
        t = S.SyntaxTree.fromText(rf.text, sm, rf.name, path, loaded.bag)
        comp.addSyntaxTree(t)
        by_path[path] = rf
        by_path[rf.name] = rf
        trees.append((rf, path, t))
    comp.getRoot()

    diags: List[Diag] = []
    for d in convert_diags(sm, comp.getAllDiagnostics()):
        if d.severity != Severity.ERROR:
            continue
        rf = by_path.get(d.loc.file) if d.loc is not None else None
        diags.append(_map(d, rf, d.loc.file) if rf is not None else d)
    for rf, path, t in trees:
        diags.extend(check_rules(t, rf, res.cfg, path))
    if not any(d.severity == Severity.ERROR for d in diags):
        diags.extend(_structure(res, comp))
    return VerifyResult("full", diags)


def _structure(res, comp) -> List[Diag]:
    diags: List[Diag] = []
    for wc in res.woven:
        pkg = comp.getPackage(wc.cls.package + "_woven")
        ct = pkg.find(wc.name) if pkg is not None else None
        if ct is None:
            diags.append(Diag(Severity.ERROR, "verify: %s not found after elaboration" % wc.name))
            continue
        if wc.concrete and ct.isAbstract:
            diags.append(Diag(Severity.ERROR, "verify: %s is registered but abstract" % wc.name,
                              wc.cls.loc))
        for slot in wc.slots.values():
            if slot.kind == MethodSlot.KIND_NEW or slot.overrides is None:
                continue
            m = ct.find(slot.name)
            if m is None or m.override is None:
                diags.append(Diag(Severity.ERROR, "verify: %s.%s does not override %s::%s"
                                  % (wc.name, slot.name, slot.overrides.owner.qname, slot.name),
                                  slot.overrides.loc))
    return diags


def verify(res, level: str, previous: Optional[dict]) -> VerifyResult:
    if level == "off":
        return VerifyResult("off")
    if previous is not None and previous.get("verified") == {
            "level": "full", "input_hash": res.input_hash, "output_hash": res.output_hash}:
        return VerifyResult("cached")
    if level == "syntax":
        return verify_syntax(res)
    return verify_full(res)
